const NBSP = "\u00A0";

/**
 * Короткие слова, которые не должны «висеть» в конце строки.
 * Они переносятся на новую строку вместе со следующим словом.
 */
const HANGING = [
  // предлоги
  "в", "во", "на", "за", "под", "подо", "над", "надо", "при", "про", "для",
  "из", "изо", "из-за", "из-под", "от", "ото", "до", "по", "к", "ко", "с",
  "со", "у", "о", "об", "обо", "без", "через", "перед", "передо", "между",
  "около", "среди", "вокруг", "после", "вместо", "кроме", "ради", "сквозь",
  // союзы и частицы
  "и", "а", "но", "да", "или", "либо", "ни", "же", "бы", "ль", "ли", "не",
  "что", "чтоб", "чтобы", "как", "когда", "где", "куда", "если", "то",
  "так", "чем", "хоть", "хотя", "пусть", "ведь", "лишь", "уже", "ещё", "еще",
  // местоимения
  "я", "мы", "ты", "вы", "он", "она", "оно", "они", "их", "им", "ее", "её",
];

/*
  Важно: в хвосте стоит [ \t\r\n]+, а не \s+.
  \s включает и сам неразрывный пробел, поэтому второй проход
  «съедал» уже поставленный NBSP и следующее короткое слово
  оставалось непривязанным: «вы\u00A0в поездках».
*/
const HANGING_RE = new RegExp(
  `(^|[\\s("«„\\u00A0])(${HANGING.join("|")})[ \\t\\r\\n]+`,
  "gi",
);

const UNITS_RE = /(\d)\s+(₽|руб\.?|%|тыс\.?|млн|млрд|км|мин|ч|г|кг|шт\.?)/gi;

/**
 * Расставляет неразрывные пробелы по правилам русской типографики.
 *
 * 1. Союзы, предлоги и частицы уходят на новую строку вместе со словом,
 *    к которому относятся.
 * 2. Тире не начинает строку — оно остаётся на строке с предыдущим словом.
 * 3. Числа не отрываются от единиц измерения и от разрядов.
 */
export function typo(input: string): string {
  let text = input
    // одиночный дефис между словами -> длинное тире
    .replace(/(\S)\s+-\s+(?=\S)/g, "$1 — ")
    // неразрывный пробел перед тире, обычный — после
    .replace(/(\S)[\s\u00A0]+([—–])[\s\u00A0]+/g, `$1${NBSP}$2 `);

  // три прохода, чтобы обработать цепочки вида «и в лесу»
  for (let i = 0; i < 3; i += 1) {
    text = text.replace(HANGING_RE, `$1$2${NBSP}`);
  }

  return text
    .replace(UNITS_RE, `$1${NBSP}$2`)
    .replace(/(\d)\s+(\d{3})/g, `$1${NBSP}$2`);
}

/** Массив строк — например, для списков и подписей. */
export function typoAll<T extends readonly string[]>(items: T): string[] {
  return items.map(typo);
}
